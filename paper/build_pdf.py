# 特殊行(标题/表格/题注/编号列表/引用条目)保持独立;行首 ** 一律视为段首
# (本文档的粗体引导语即段落分隔);[n] 条目仅在 References 节内独立。
def _join_wrapped(lines_):
    out, buf = [], []
    in_ref = False

    def flush():
        if buf:
            out.append(" ".join(buf))
            buf.clear()

    for ln in lines_:
        s = ln.strip()
        if s.startswith("## "):
            in_ref = s[3:].strip() == "References"
        if (not s or s == "---" or s.startswith("#") or s.startswith("|")
                or re.match(r"^\s*[-*]\s", ln)
                or (in_ref and re.match(r"^\[\d+\]", s))
                or s.startswith("*Correction note")):
            flush()
            out.append(ln)
        elif re.match(r"^\d+\.\s", s) or s.startswith("**"):
            # 编号条目/粗体引导语 = 段落起点:自身开新段,续行随后合入
            flush()
            buf.append(s)
        else:
            buf.append(s)
    flush()
    return out


